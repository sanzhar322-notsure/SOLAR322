/**
 * Evidence cards. Levels are qualitative and defined (no invented numeric
 * scores):
 *  - well:         consistent evidence from multiple high-quality studies or
 *                  formal consensus/agency assessments.
 *  - supported:    good evidence for the core claim, with important limits
 *                  (small samples, lab conditions, effect size, populations).
 *  - preliminary:  early, mechanistic, animal/cell or small human studies.
 *  - disputed:     the claim conflicts with stronger or consensus evidence.
 *  - insufficient: little or no independent evidence for the claim as stated.
 *
 * Proponents’ positions are paraphrased, not quoted, with links to their own
 * writing so you can read them in full. `researchNote` flags where the
 * attribution could not be fully verified against primary text in this build.
 */
